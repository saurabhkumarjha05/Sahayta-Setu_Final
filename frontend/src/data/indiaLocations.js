// Helper function: get all sorted state/UT names
export const getStates = () => {
  return Object.keys(INDIA_LOCATIONS).sort();
};

// Helper function: get sorted district names for a given state
export const getDistrictsByState = (stateName) => {
  if (!stateName || !INDIA_LOCATIONS[stateName]) return [];
  return INDIA_LOCATIONS[stateName].map((d) => d.name).sort();
};

// Helper function: get district details (lat, lng, name) for state & district
export const getDistrictCoordinates = (stateName, districtName) => {
  if (!stateName || !districtName || !INDIA_LOCATIONS[stateName]) return null;
  const match = INDIA_LOCATIONS[stateName].find(
    (d) => d.name.toLowerCase() === districtName.toLowerCase()
  );
  if (match) {
    return { lat: match.lat, lng: match.lng, name: match.name, state: stateName };
  }
  return null;
};

// Fallback search across all states if state name is omitted or unknown
export const findDistrictCoordinates = (districtName, stateName = null) => {
  if (!districtName) return null;
  const dLower = String(districtName).trim().toLowerCase();

  if (stateName && INDIA_LOCATIONS[stateName]) {
    const found = INDIA_LOCATIONS[stateName].find(
      (d) => d.name.toLowerCase() === dLower
    );
    if (found) {
      return { lat: found.lat, lng: found.lng, name: found.name, state: stateName };
    }
  }

  for (const [state, districts] of Object.entries(INDIA_LOCATIONS)) {
    const match = districts.find((d) => d.name.toLowerCase() === dLower);
    if (match) {
      return { lat: match.lat, lng: match.lng, name: match.name, state };
    }
  }

  return null;
};
